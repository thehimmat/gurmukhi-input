"""Golden outputs from gurmukhi-transliterate's GurmukhiLegacy.convert, for test/golden.json.

    python3 scripts/golden.py /path/to/gurmukhi-transliterate > test/golden.json
"""
import csv
import json
import random
import sys
from pathlib import Path

repo = Path(sys.argv[1])
sys.path.insert(0, str(repo))
from gurmukhi_transliterate.legacy import LAYOUTS, GurmukhiLegacy  # noqa: E402

cases = []


def add(source, encoding, text):
    r = GurmukhiLegacy.convert(text, encoding)
    cases.append({
        'source': source, 'encoding': encoding, 'input': text, 'text': r.text,
        'warnings': [[w.position, w.char, w.kind] for w in r.warnings],
    })


# Real text from PDFs, with their hand-checked Unicode
fixtures = repo / 'tests/fixtures/legacy'
for f in sorted(fixtures.glob('*.txt')):
    stem, enc = f.name.rsplit('.', 2)[:2]
    if enc == 'unicode':
        continue
    add(f'fixture:{f.name}', 'anmollipi' if enc == 'gurbaniakhar' else enc, f.read_text())

# GurbaniAkhar lines from the gold corpus
for row in csv.DictReader(open(repo / 'tests/fixtures/gold/lines.tsv'), delimiter='\t'):
    add(f'gold:{row["id"]}', 'anmollipi', row['gurbaniakhar'])

# Seeded random typing in every layout: exercises sihari reordering, orphans,
# subjoined letters typed after vowel signs, overlays and unmapped keys
rng = random.Random(1469)
for name, layout in LAYOUTS.items():
    alphabet = list(layout.keys) + [c for c, _ in layout.combos.items()] + list(layout.passthrough) + ['§', 'Ω', 'z', '√']
    for n in range(300):
        add(f'fuzz:{name}:{n}', name, ''.join(rng.choice(alphabet) for _ in range(rng.randint(1, 24))))

fonts = ['CKPHAK+Asees', 'GurbaniAkharThick', 'AnmolLipi', 'Joy', 'Satluj-Bold', 'SONY_Font', 'gurbani_web',
         'AnandpurSahib', 'Arial', 'ABCDEF+GurbaniLipiLight', 'Prabhki', 'unknown-font', 'Lord Bold']
print(json.dumps({
    'source': 'Generated by scripts/golden.py from gurmukhi-transliterate GurmukhiLegacy',
    'cases': cases,
    'fonts': [[f, GurmukhiLegacy.encoding_for_font(f)] for f in fonts],
}, ensure_ascii=False, separators=(',', ':')))
