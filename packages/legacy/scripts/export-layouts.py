"""Export the legacy font layouts from gurmukhi-transliterate to src/layouts.data.ts.

The Python package is the source of truth for the key maps (they were derived by
rendering each font's glyphs). Run after it changes:

    python3 scripts/export-layouts.py /path/to/gurmukhi-transliterate > src/layouts.data.ts
"""
import json
import sys

sys.path.insert(0, sys.argv[1])
from gurmukhi_transliterate.legacy import LAYOUTS  # noqa: E402

# Mac Roman bytes 0x80-0xFF as text, for the Satluj repair (see convert.ts)
mac_roman = bytes(range(0x80, 0x100)).decode('mac_roman')
# Windows-1252 bytes 0x80-0xFF as text; bytes it leaves undefined read as Latin-1
cp1252 = ''.join(bytes([b]).decode('cp1252', errors='strict') if b not in (0x81, 0x8D, 0x8F, 0x90, 0x9D)
                 else bytes([b]).decode('latin-1') for b in range(0x80, 0x100))

layouts = {
    name: {
        'name': l.name,
        'label': l.label,
        'keys': l.keys,
        'combos': list(l.combos.items()),   # order matters: first match wins
        'sihari': sorted(l.sihari),
        'passthrough': sorted(l.passthrough),
        'fonts': list(l.fonts),
        'oneNasalKey': l.one_nasal_key,
        'joinDandas': l.join_dandas,
        'macRomanRepair': l.mac_roman_repair,
    }
    for name, l in LAYOUTS.items()
}

print('// Generated by scripts/export-layouts.py from gurmukhi-transliterate')
print('// (gurmukhi_transliterate/legacy.py, _legacy_layouts.py). Do not edit by hand.')
print("import type { LayoutData } from './types';")
print()
print('export const LAYOUT_DATA: Record<string, LayoutData> = ' + json.dumps(layouts, ensure_ascii=False, indent=1) + ';')
print()
print('export const MAC_ROMAN_HIGH = ' + json.dumps(mac_roman, ensure_ascii=False) + ';')
print('export const CP1252_HIGH = ' + json.dumps(cp1252) + ';')
